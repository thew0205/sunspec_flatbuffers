#!/usr/bin/env python3
"""Generates src/models/model<id>.cpp files (and wires them into
include/c_model_definition.h and src/model_definition.cpp) from the canonical
SunSpec model JSON in models/json/model_<id>.json.

This targets the hand-authored SunspecModelDef/SunspecGroupDef/SunspecPointDef
struct literal format (see src/models/model1.cpp for the definition this mapping
was reverse-engineered from), not the FlatBuffers/nakedbytes/protobuf
array-of-bytes adapters.

Re-run this whenever models/json/*.json changes, or the c_model_definition.h
literal shape changes. A model<id>.cpp is only overwritten if it still carries
the "// Auto-generated ... Unreviewed" banner this script stamps on its output;
a file without that banner is treated as hand-corrected and left untouched.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_DIR = ROOT / "models" / "json"
MODELS_OUT_DIR = ROOT / "src" / "models"
HEADER_PATH = ROOT / "include" / "c_model_definition.h"
DEFINITION_CPP_PATH = ROOT / "src" / "model_definition.cpp"

GENERATED_BANNER = "// Auto-generated by models/generate_model_definition_cpp.py"

# Maps a JSON point "type" string to the c_model_definition.h struct/ctor name
# (also the SunspecPointData_<name> enum suffix, kAcc32 included, since that
# enumerator is miscapitalized with no leading lowercase k).
TYPE_MAP = {
    "int16": "kSint16",
    "int32": "kSint32",
    "int64": "kSint64",
    "raw16": "kRaw16",
    "uint16": "kUint16",
    "uint32": "kUint32",
    "uint64": "kUint64",
    "acc16": "kAcc16",
    "acc32": "kAcc32",
    "acc64": "kAcc64",
    "bitfield16": "kBitfield16",
    "bitfield32": "kBitfield32",
    "bitfield64": "kBitfield64",
    "enum16": "kEnum16",
    "enum32": "kEnum32",
    "float32": "kFloat32",
    "float64": "kFloat64",
    "string": "kStringx",
    "sunssf": "kSunsSf",
    "pad": "kPad16",
    "ipaddr": "kIpAddr",
    "ipv6addr": "kIpv6Addr",
    "eui48": "kEui48",
}


def cpp_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def format_point(p: dict, indent: str) -> str:
    name = p["name"]
    ctor_name = TYPE_MAP[p["type"]]
    data_type_enum = f"SunspecPointData_{ctor_name}"
    size = p["size"]
    units = p.get("units", "")
    access = "SunspecPointAccessType_kRW" if p.get("access") == "RW" else "SunspecPointAccessType_kR"
    mandatory = "SunspecPointMandatoryType_kM" if p.get("mandatory") == "M" else "SunspecPointMandatoryType_kO"
    label = p.get("label", "")

    sf = p.get("sf", "")
    trailing_comment = ""
    if isinstance(sf, int):
        trailing_comment = f"  // NOTE(generated): source JSON has a constant sf={sf}, not a point reference; not representable here."
        sf = ""

    data_arg = "{}"
    if "value" in p:
        value = p["value"]
        if p["type"] == "uint16" and isinstance(value, int):
            data_arg = f"{ctor_name}({value})"
        else:
            trailing_comment += f"  // NOTE(generated): source JSON has value={value!r} for type {p['type']!r}, not yet handled by the generator; defaulted."

    return (
        f"{indent}{{{cpp_str(name)}, 1, {cpp_str('')}, {cpp_str(sf)}, "
        f"{cpp_str(units)}, {size}, {data_type_enum}, {data_arg}, {access}, {mandatory}, "
        f"{cpp_str(label)}}},{trailing_comment}"
    )


def format_group(g: dict, indent: str) -> str:
    name = g.get("name", "")
    label = g.get("label", "")
    count = g.get("count", 1)
    if isinstance(count, str):
        # 0 is the sentinel the reader/writer use to mean "look the real count
        # up at runtime via count_id" (see SunspecGroupReader::initGroups()).
        count_literal = "0"
        count_id = count
    else:
        count_literal = str(count)
        count_id = ""
    group_type = "SunspecGroupType_kSync" if g.get("type") == "sync" else "SunspecGroupType_kGroup"

    points = g.get("points", [])
    groups = g.get("groups", [])

    lines = []
    lines.append(f"{indent}{{")
    lines.append(f"{indent}    {cpp_str(name)},")
    lines.append(f"{indent}    {cpp_str(label)},")
    lines.append(f"{indent}    {count_literal},")
    lines.append(f"{indent}    {cpp_str(count_id)},")
    lines.append(f"{indent}    {group_type},")
    lines.append(f"{indent}    {{")
    for p in points:
        lines.append(format_point(p, indent + "        "))
    lines.append(f"{indent}    }},")
    lines.append(f"{indent}    {{")
    for sub in groups:
        lines.append(format_group(sub, indent + "        "))
        lines[-1] += ","
    lines.append(f"{indent}    }},")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def generate_model_cpp(model_id: int, data: dict) -> str:
    group = data["group"]
    model_label = group.get("label", group.get("name", ""))
    group_literal = format_group(group, "        ")

    return (
        f"{GENERATED_BANNER} from models/json/model_{model_id}.json.\n"
        f"// Unreviewed -- regenerate rather than hand-edit unless you also fix up the generator.\n"
        f'#include "c_model_definition.h"\n\n'
        f"const SunspecModelDef SunspecModelDef::modelDef{model_id}{{\n"
        f"        SunspecModelList_kModel{model_id},\n"
        f"        {cpp_str(model_label)},\n"
        f"{group_literal},\n"
        f"    }};\n"
    )


def load_models() -> dict:
    models = {}
    for path in sorted(JSON_DIR.glob("model_*.json")):
        data = json.loads(path.read_text())
        models[data["id"]] = data
    return models


def update_header(model_ids: list[int]) -> None:
    text = HEADER_PATH.read_text()

    enum_start = text.index("enum SunspecModelList : uint16_t\n{")
    enum_open_brace = text.index("{", enum_start)
    enum_close = text.index("kModelEnd", enum_open_brace)
    new_enum_body = "\n"
    for mid in model_ids:
        new_enum_body += f"    kModel{mid} = {mid}, /**< Definition for model{mid} */\n"
    new_enum_body += "\n    "
    text = text[: enum_open_brace + 1] + new_enum_body + text[enum_close:]

    decl_marker = "static const SunspecModelDef modelDef1;"
    decl_start = text.rindex("/**", 0, text.index(decl_marker))
    decl_end = text.index("};", text.index(decl_marker))
    decl_end = text.rindex("\n", 0, decl_end) + 1
    new_decls = ""
    for mid in model_ids:
        new_decls += (
            f"    /**\n"
            f"     * @brief Static definition for Model {mid}.\n"
            f"     */\n"
            f"    static const SunspecModelDef modelDef{mid};\n\n"
        )
    text = text[:decl_start] + new_decls.rstrip("\n") + "\n" + text[decl_end:]

    HEADER_PATH.write_text(text)


def update_definition_cpp(model_ids: list[int]) -> None:
    text = DEFINITION_CPP_PATH.read_text()
    start = text.index("modelDefList.push_back(&modelDef1);")
    start = text.rindex("\n", 0, start) + 1
    end = text.index("\n\n", start) + 1
    new_body = ""
    for mid in model_ids:
        new_body += f"        modelDefList.push_back(&modelDef{mid});\n"
    text = text[:start] + new_body + text[end:]
    DEFINITION_CPP_PATH.write_text(text)


def main() -> None:
    models = load_models()
    all_ids = sorted(models.keys())

    written, preserved = [], []
    for mid in all_ids:
        out_path = MODELS_OUT_DIR / f"model{mid}.cpp"
        if out_path.exists():
            existing = out_path.read_text()
            if not existing.startswith(GENERATED_BANNER):
                preserved.append(mid)
                continue
        out_path.write_text(generate_model_cpp(mid, models[mid]))
        written.append(mid)

    # update_header(all_ids)
    # update_definition_cpp(all_ids)

    print(f"Wrote {len(written)} model .cpp files: {written}")
    print(f"Preserved {len(preserved)} hand-corrected model .cpp files (no generated banner): {preserved}")
    print(f"Header and model_definition.cpp now wire up all {len(all_ids)} models.")


if __name__ == "__main__":
    main()
