#!/usr/bin/env python3
"""Generates src/models/json/model_json_<id>.cpp files: each one embeds a
model's canonical JSON (models/json/model_<id>.json), minified, as a static
const char* string literal, for the SUNSPEC_JSON_IMPLEMENTATION adapter
(see include/adapters/json/sunspec_json_definition.h) to parse at runtime.

Usage: models/generate_model_json_cpp.py <id> [<id> ...]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_DIR = ROOT / "models" / "json"
OUT_DIR = ROOT / "src" / "models" / "json"


def c_escape(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return "".join(out)


def generate(model_id: int) -> str:
    src_path = JSON_DIR / f"model_{model_id}.json"
    data = json.loads(src_path.read_text())
    minified = json.dumps(data, separators=(",", ":"))
    escaped = c_escape(minified)

    return (
        f"// Auto-generated by models/generate_model_json_cpp.py from models/json/model_{model_id}.json.\n"
        f"// Do not hand-edit -- regenerate from the source JSON instead.\n"
        f'extern const char *const kModelJsonText{model_id} = "{escaped}";\n'
    )


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for arg in sys.argv[1:]:
        model_id = int(arg)
        out_path = OUT_DIR / f"model_json_{model_id}.cpp"
        out_path.write_text(generate(model_id))
        print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
